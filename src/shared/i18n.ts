export function resolveLanguage(preference: LanguagePreference, vscodeLanguage: string): AppLanguage {
  if (preference !== "auto") {
    return preference;
  }
  const normalized = vscodeLanguage.toLowerCase();
  if (normalized.startsWith("vi")) {
    return "vi";
  }
  if (normalized.startsWith("zh")) {
    return "zh-cn";
  }
  return "en";
}

export function translate(
  language: AppLanguage,
  message: string,
  values: TranslationValues = {}
): string {
  const localized = language === "vi" ? vi[message] : language === "zh-cn" ? zhCn[message] : undefined;
  return (localized ?? message).replace(/\{(\w+)\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : match
  );
}
